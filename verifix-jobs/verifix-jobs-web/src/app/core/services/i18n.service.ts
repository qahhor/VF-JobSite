import { Injectable, signal, computed } from '@angular/core';

export type Lang = 'uz_lat' | 'uz_cyr' | 'ru' | 'en' | 'kk' | 'tg' | 'ky';

export interface LangOption {
  code: Lang;
  name: string;
  nativeName: string;
  flag: string;
}

@Injectable({ providedIn: 'root' })
export class I18nService {
  private currentLang = signal<Lang>(this.loadLang());

  lang = this.currentLang.asReadonly();
  dir = computed(() => 'ltr');

  static readonly LANGUAGES: LangOption[] = [
    { code: 'uz_lat', name: 'Uzbek (Latin)', nativeName: "O'zbekcha", flag: '🇺🇿' },
    { code: 'uz_cyr', name: 'Uzbek (Cyrillic)', nativeName: 'Ўзбекча', flag: '🇺🇿' },
    { code: 'ru', name: 'Russian', nativeName: 'Русский', flag: '🇷🇺' },
    { code: 'en', name: 'English', nativeName: 'English', flag: '🇬🇧' },
    { code: 'kk', name: 'Kazakh', nativeName: 'Қазақша', flag: '🇰🇿' },
    { code: 'tg', name: 'Tajik', nativeName: 'Тоҷикӣ', flag: '🇹🇯' },
    { code: 'ky', name: 'Kyrgyz', nativeName: 'Кыргызча', flag: '🇰🇬' },
  ];

  get languages() { return I18nService.LANGUAGES; }

  setLang(lang: Lang) {
    this.currentLang.set(lang);
    localStorage.setItem('vjw_lang', lang);
    document.documentElement.lang = lang.replace('_', '-');
  }

  t(key: string): string {
    const lang = this.currentLang();
    const translations = TRANSLATIONS[lang] || TRANSLATIONS['uz_lat'];
    return translations[key] || TRANSLATIONS['uz_lat'][key] || key;
  }

  private loadLang(): Lang {
    const saved = localStorage.getItem('vjw_lang') as Lang;
    if (saved && I18nService.LANGUAGES.some(l => l.code === saved)) return saved;
    const nav = navigator.language?.toLowerCase() || '';
    if (nav.startsWith('ru')) return 'ru';
    if (nav.startsWith('en')) return 'en';
    if (nav.startsWith('kk')) return 'kk';
    if (nav.startsWith('tg')) return 'tg';
    if (nav.startsWith('ky')) return 'ky';
    return 'uz_lat';
  }
}

